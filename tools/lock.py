#!/usr/bin/env python3
"""Helpers for tools/make-lock.sh: a mod's Cargo.lock against the game's.

  lock.py align MOD_LOCK GAME_LOCK   every package the game also locks takes the game's record
                                     (version and edges), with what those edges need; then what
                                     the mod cannot reach is dropped
  lock.py check RESOLVED GAME_LOCK [MOD_LOCK]
                                     the launcher's rule for client builds against the prebuilt
                                     game: a package the game locks keeps its version and gains no
                                     edge the game's record lacks; every registry package is pinned
"""
import sys, tomllib


def align(mod_lock, game_lock):
    text = open(mod_lock).read()
    mod = tomllib.loads(text)
    game = tomllib.load(open(game_lock, 'rb'))
    G = {(p['name'], p['version']): p for p in game['package'] if p.get('source', '').startswith('registry+')}
    gnames = {}
    for (n, v) in G: gnames.setdefault(n, []).append(v)
    pk = {(p['name'], p['version']): p for p in mod['package']}
    # Replace shared records by the game's.
    for key in list(pk):
        if key in G:
            pk[key] = G[key]
    def resolve(dep, versions):
        parts = dep.split(' ')
        name = parts[0]
        if len(parts) > 1:
            return (name, parts[1])
        vs = versions.get(name, [])
        if len(vs) != 1:
            raise SystemExit(f'ambiguous {dep}: {vs}')
        return (name, vs[0])
    # Add what the game's records reach, from the game's lock.
    changed = True
    while changed:
        changed = False
        for key, p in list(pk.items()):
            for dep in p.get('dependencies', []):
                versions = gnames if key in G else {}
                if key not in G:
                    for (n, v) in pk: versions.setdefault(n, []).append(v)
                d = resolve(dep, versions)
                if d not in pk:
                    if d not in G: raise SystemExit(f'{key} needs {d}, which neither lock has')
                    pk[d] = G[d]; changed = True
    # Keep only what the root reaches.
    roots = [k for k, p in pk.items() if 'source' not in p]
    byname = {}
    for (n, v) in pk: byname.setdefault(n, []).append(v)
    seen = set(); todo = list(roots)
    while todo:
        k = todo.pop()
        if k in seen: continue
        seen.add(k)
        for dep in pk[k].get('dependencies', []):
            parts = dep.split(' ')
            d = (parts[0], parts[1]) if len(parts) > 1 else (parts[0], byname[parts[0]][0]) if len(byname[parts[0]]) == 1 else None
            if d is None:
                raise SystemExit(f'ambiguous {dep} in {k}')
            todo.append(d)
    kept = [pk[k] for k in sorted(seen)]
    # Dependency strings need a version only where a name has several versions.
    names = {}
    for (n, v) in seen: names.setdefault(n, []).append(v)
    def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    out = ['# This file is automatically @generated by Cargo.', '# It is not intended for manual editing.', f'version = {mod.get("version", 4)}', '']
    for p in kept:
        out.append('[[package]]')
        out.append(f'name = {q(p["name"])}')
        out.append(f'version = {q(p["version"])}')
        if 'source' in p: out.append(f'source = {q(p["source"])}')
        if 'checksum' in p: out.append(f'checksum = {q(p["checksum"])}')
        deps = []
        for dep in p.get('dependencies', []):
            parts = dep.split(' ')
            n = parts[0]
            v = parts[1] if len(parts) > 1 else byname[n][0]
            deps.append(f'{n} {v}' if len(names[n]) > 1 else n)
        if deps:
            out.append('dependencies = [')
            out.extend(f' {q(d)},' for d in sorted(deps))
            out.append(']')
        out.append('')
    open(mod_lock, 'w').write('\n'.join(out))
    print(f'{mod_lock}: {len(kept)} packages')


def check(*paths):
    """Exits with 1 when the resolved lock breaks the rule."""
    def load(p):
        pk = tomllib.load(open(p, 'rb'))['package']
        by = {}
        for x in pk: by.setdefault(x['name'], []).append(x['version'])
        out = {}
        for x in pk:
            deps = set()
            for d in x.get('dependencies', []):
                parts = d.split(' ')
                deps.add((parts[0], parts[1] if len(parts) > 1 else by[parts[0]][0]))
            out[(x['name'], x['version'])] = (x, deps)
        return out
    R, G = load(paths[0]), load(paths[1])
    P = load(paths[2]) if len(paths) > 2 else R
    gnames = {n for n, _ in G}
    bad = 0
    for key, (x, deps) in R.items():
        if 'source' not in x: continue
        if key in G:
            extra = {d for d in deps if d not in G[key][1] and d[0] in {n for n, _ in G[key][1]}}
            if extra: print('edge moved:', key, sorted(extra)); bad += 1
        elif x['name'] in gnames and (key not in P or P[key][1] != deps):
            print('version moved:', key, 'game has', sorted(v for n, v in G if n == x['name'])); bad += 1
        if key not in G and key not in P:
            print('not pinned:', key); bad += 1
    print('ok' if not bad else f'{bad} problems')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    command, *args = sys.argv[1:]
    {'align': align, 'check': check}[command](*args)
